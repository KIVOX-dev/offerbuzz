/**
 * Writes every template as a standalone .html file (placeholders intact) for pasting into Brevo,
 * plus an index listing subject lines and parameters.
 * Run: npm run emails:export
 */
import fs from 'node:fs';
import path from 'node:path';
import { TEMPLATES, campaignHtml, rawHtml } from './templates';

const outDir = path.resolve(__dirname, '../../../../infra/brevo-templates');
fs.mkdirSync(outDir, { recursive: true });

for (const tpl of TEMPLATES) {
  fs.writeFileSync(path.join(outDir, `${tpl.id}.html`), rawHtml(tpl));
  const campaign = campaignHtml(tpl);
  if (campaign) fs.writeFileSync(path.join(outDir, `${tpl.id}.campaign.html`), campaign);
}

const rows = TEMPLATES.map(
  (t) => `| \`${t.id}.html\` | ${t.kind} | ${t.phase} | ${t.subject.replace(/\|/g, '\\|')} | ${t.params.map((p) => `\`${p}\``).join(', ')} |`,
);
fs.writeFileSync(
  path.join(outDir, 'README.md'),
  `# Brevo email templates

Generated by \`npm run emails:export\` from \`apps/api/src/emails\`. Do not edit the HTML by hand: change the source and re-export.

How to use in Brevo: Transactional (or Campaigns) -> Templates -> New template -> HTML editor -> paste the file.
Set the subject from the table. Variables use \`{{ params.name }}\`; pass them in the API call's \`params\`.
Marketing templates contain Brevo's \`{{ unsubscribe }}\` link.

| File | Type | Phase | Subject | Params |
|---|---|---|---|---|
${rows.join('\n')}
`,
);
console.log(`Wrote ${TEMPLATES.length} templates to ${outDir}`);
